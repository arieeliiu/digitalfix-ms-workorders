-- Migración aditiva para Oracle: historial de auditoría de órdenes.
-- Ejecutar con el propietario del esquema. No modifica ordenes_trabajo ni sus datos.
-- Idempotente: si Hibernate ddl-auto=update ya creó la tabla o el índice, no hace nada.
-- Sin FK a ordenes_trabajo a propósito: el historial sobrevive a la eliminación de la orden.
DECLARE
    cantidad NUMBER;
BEGIN
    SELECT COUNT(*) INTO cantidad FROM USER_TABLES WHERE TABLE_NAME = 'HISTORIAL_ORDENES';
    IF cantidad = 0 THEN
        EXECUTE IMMEDIATE '
            CREATE TABLE historial_ordenes (
                id              NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                orden_id        NUMBER(19)         NOT NULL,
                accion          VARCHAR2(20 CHAR)  NOT NULL,
                estado_anterior VARCHAR2(30 CHAR),
                estado_nuevo    VARCHAR2(30 CHAR),
                tecnico_id      VARCHAR2(100 CHAR),
                actor_id        VARCHAR2(100 CHAR) NOT NULL,
                actor_roles     VARCHAR2(100 CHAR),
                fecha           TIMESTAMP(6)       NOT NULL,
                CONSTRAINT ck_historial_ordenes_accion
                    CHECK (accion IN (''CREACION'', ''CAMBIO_ESTADO'', ''ELIMINACION'',
                        ''EDICION_DATOS'', ''EDICION_CONTACTOS'', ''EDICION_REPUESTOS''))
            )';
    END IF;
    SELECT COUNT(*) INTO cantidad FROM USER_INDEXES WHERE INDEX_NAME = 'IX_HISTORIAL_ORDENES_ORDEN';
    IF cantidad = 0 THEN
        EXECUTE IMMEDIATE 'CREATE INDEX ix_historial_ordenes_orden ON historial_ordenes (orden_id)';
    END IF;
END;
/
